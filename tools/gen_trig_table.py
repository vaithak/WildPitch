#!/usr/bin/env python3
"""Generate src/sim/trig_table.h: quarter-wave sine table in Q16.16.
Angles in the sim are 'binary angles' (uint16, 65536 = full turn). We store
sin for 0..90 deg in 4097 entries (index = angle >> 2 within quarter).
Generated once; committed. Re-run only if the format changes."""
import math
N = 4096
vals = [round(math.sin(i * math.pi / 2 / N) * 65536) for i in range(N + 1)]
with open("src/sim/trig_table.h", "w") as f:
    f.write("/* GENERATED by tools/gen_trig_table.py - do not edit. */\n")
    f.write("#ifndef WP_TRIG_TABLE_H\n#define WP_TRIG_TABLE_H\n#include <stdint.h>\n")
    f.write(f"#define WP_SIN_QUARTER_N {N}\n")
    f.write(f"static const int32_t wp_sin_quarter[{N+1}] = {{\n")
    for i in range(0, N + 1, 12):
        f.write("  " + ", ".join(str(v) for v in vals[i:i+12]) + ",\n")
    f.write("};\n#endif\n")
